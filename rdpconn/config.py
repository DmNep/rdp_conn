"""Константы канала rdp_conn.

Единственный источник истины по значениям протокола; спецификация —
docs/protocol.md. Обе стороны (отправитель и приёмник) импортируют именно этот
модуль, поэтому разъезд здесь означает рассинхронизацию сторон, а не опечатку.

Внешних зависимостей нет намеренно: канал нужен ровно тогда, когда на второй
машине нельзя ничего поставить и поднять, поэтому он обязан запускаться
интерпретатором «как есть». Отсюда же отсутствие numpy: звуковой предшественник
тянул его для DSP, буферу обмена арифметика не нужна.
"""

from __future__ import annotations

# --- Кадрирование -----------------------------------------------------------

# Байт начала кадра. Совпадает с HDLC-флагом: в тексте слота он всё равно
# прячется за base64, но совпадение с аудио-предшественником сохраняет
# готовый разбор кадра байт-в-байт.
SYNC_BYTE = 0x7E

# Фиксированная часть: sync | type | seq | len(2) | payload | crc(2).
MAX_PAYLOAD = 240

# Сколько раз повторить кадр без подтверждения. Три, а не один: один потерянный
# ответ — штатная ситуация (слот в этот момент держит человек), и считать
# обмен сломанным после него значит ретранслировать то, что уже дошло.
MAX_RETRY = 3

# --- Типы кадров ------------------------------------------------------------

ACK = 0x03
NAK = 0x04
PING = 0x41
PONG = 0x42
CMD = 0x10
NOTE = 0x22

# Порядок словаря значим: hex-дамп и разбор опираются на него как на таблицу.
FRAME_TYPES: dict[int, str] = {
    ACK: "ACK",
    NAK: "NAK",
    PING: "PING",
    PONG: "PONG",
    CMD: "CMD",
    NOTE: "NOTE",
}

# Типы, несущие человекочитаемый ответ. Отправитель печатает их и не тратит на
# них попытку: посторонний ответ — часть разговора, а не его отсутствие.
REPLY_TYPES = (NOTE,)

# Причины NAK (docs/protocol.md 5).
NAK_CRC = 0x01
NAK_TYPE = 0x02
NAK_LENGTH = 0x03

# --- Текст ------------------------------------------------------------------

# Кодовая страница payload. Буферный канал — это Windows<->Windows, обе
# половины здесь cmd.exe, поэтому cp866 и кириллица сохраняется. У
# звукового предшественника была cp437: там другая сторона — Linux-терминал, а
# cp437 кириллицы не содержит вовсе и молча превращала текст в '?' через
# errors="replace".
CODEPAGE = "cp866"
