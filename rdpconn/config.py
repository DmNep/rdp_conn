"""Константы канала rdp_conn.

Единственный источник истины по значениям протокола; спецификация —
docs/protocol.md. Обе стороны (отправитель и приёмник) импортируют именно этот
модуль, поэтому разъезд здесь означает рассинхронизацию сторон, а не опечатку.

Внешних зависимостей нет намеренно: канал нужен ровно тогда, когда на второй
машине нельзя ничего поставить и поднять, поэтому он обязан запускаться
интерпретатором «как есть». Отсюда же отсутствие numpy: звуковой предшественник
тянул его для DSP, буферу обмена арифметика не нужна.
"""

from __future__ import annotations

# --- Кадрирование -----------------------------------------------------------

# Байт начала кадра. Совпадает с HDLC-флагом: в тексте слота он всё равно
# прячется за base64, но совпадение с аудио-предшественником сохраняет
# готовый разбор кадра байт-в-байт.
SYNC_BYTE = 0x7E

# Фиксированная часть: sync | type | seq | len(2) | payload | crc(2).
MAX_PAYLOAD = 240

# Потолок вывода --exec. Кадр держит MAX_PAYLOAD, поэтому ответ идёт
# несколькими NOTE; без потолка одна длинная команда забила бы слот.
EXEC_OUTPUT_LIMIT = 4096

# Ячеек одной стороны в тексте слота. Ответ --exec пишется пачкой быстрее,
# чем собеседник успевает прочитать буфер: ACK, затем каждый NOTE. Если
# история короче этой пачки, следующая запись стирает ACK и начало вывода.
# Лишняя ячейка — служебный кадр (PONG), который может лечь сразу после
# пачки, пока слот ещё не прочитан.
_REPLY_NOTES = (EXEC_OUTPUT_LIMIT + MAX_PAYLOAD - 1) // MAX_PAYLOAD
HISTORY_SLOTS = 1 + _REPLY_NOTES + 1

# Независимые короткие команды одного снимка. Ответ на каждую — ACK и NOTE,
# и оба должны поместиться в HISTORY_SLOTS ответной стороны. Команда длиннее
# кадра в этот счётчик не входит: её куски занимают снимок сами.
BATCH_COMMANDS = HISTORY_SLOTS // 2

# Запас к измеренному пределу повтора снимка: предел × 1.33.
# На стенде повтор ещё доходил при 0.7 с и начинал стирать ответ при 0.6 с;
# 0.7 × 1.33 = 0.94 с. Пока замер не сделан, повтор ждёт 1.0 с.
# Формат кадра от замера не меняется.
PACE_MARGIN = 1.33
PACE_STEP_S = 0.1
PACE_FLOOR_S = 0.4
PACE_CEILING_S = 1.5
PACE_TRIES = 3
# Простой без команд, после которого замер повторяют. Heartbeat в этот
# простой не входит: его кадры идут и на живом тихом канале.
PACE_IDLE_S = 180.0

# Сколько раз повторить кадр без подтверждения. Три, а не один: один потерянный
# ответ — штатная ситуация (слот в этот момент держит человек), и считать
# обмен сломанным после него значит ретранслировать то, что уже дошло.
MAX_RETRY = 3

# --- Типы кадров ------------------------------------------------------------

ACK = 0x03
NAK = 0x04
PING = 0x41
PONG = 0x42
CMD = 0x10
NOTE = 0x22

# Порядок словаря значим: hex-дамп и разбор опираются на него как на таблицу.
FRAME_TYPES: dict[int, str] = {
    ACK: "ACK",
    NAK: "NAK",
    PING: "PING",
    PONG: "PONG",
    CMD: "CMD",
    NOTE: "NOTE",
}

# Типы, несущие человекочитаемый ответ. Отправитель печатает их и не тратит на
# них попытку: посторонний ответ — часть разговора, а не его отсутствие.
REPLY_TYPES = (NOTE,)

# Причины NAK (docs/protocol.md 5).
NAK_CRC = 0x01
NAK_TYPE = 0x02
NAK_LENGTH = 0x03

# --- Текст ------------------------------------------------------------------

# Кодовая страница payload. Буферный канал — это Windows<->Windows, обе
# половины здесь cmd.exe, поэтому cp866 и кириллица сохраняется. У
# звукового предшественника была cp437: там другая сторона — Linux-терминал, а
# cp437 кириллицы не содержит вовсе и молча превращала текст в '?' через
# errors="replace".
CODEPAGE = "cp866"
